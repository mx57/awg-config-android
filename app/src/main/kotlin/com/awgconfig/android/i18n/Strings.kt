/** Текущий язык. */
val LocalStrings = staticCompositionLocalOf<Map<String, String>> { Strings.ru }
val LocalLang = staticCompositionLocalOf<String> { "ru" }

/** Локализованная строка с подстановкой %d. */
fun tr(map: Map<String, String>, key: String, vararg args: Any): String {
